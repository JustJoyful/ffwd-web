// Writes app/model/canary-reference.json: what the NATIVE llama.cpp says to the WebGPU canary prompt (greedy), so the
// browser can tell a WebGPU path that computes the right thing from one that does not (app/model/canary.js).
//
// Reproduce:  llama-server -m <the Q5_K_M gguf> -ngl 0 -c 4096 -np 1 --cache-ram 0 --port 8099   (llama.cpp b12032)
//             node scripts/make-canary-reference.mjs --server http://127.0.0.1:8099 --gguf <the same file> [--dry]
// The server must serve the SAME file as app/model/config.js (--gguf makes the script check its sha256) and the script
// records the llama.cpp build the server reports. CPU, not GPU, so the reference is the plain float path.
//
// The prompt is the real protocol (the agent chat template, the real system prompt, a real-shaped first user turn):
// in-distribution so the model is confident and greedy decoding is stable across kernels (the log-probability gap
// between the best and second-best token at each of the 20 steps is recorded in stepMargins). Its reply is the start of a "spec" action. Everything the browser needs is in the JSON: it
// never rebuilds the prompt.
import { createHash } from "node:crypto";
import { createReadStream, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { renderChat } from "../app/agent/chat-template.js";
import { MODEL } from "../app/model/config.js";

const arg = (k, d) => {
  const i = process.argv.indexOf(`--${k}`);
  return i < 0 ? d : process.argv[i + 1];
};
const SERVER = arg("server", "http://127.0.0.1:8099");
const GGUF = arg("gguf");
const DRY = process.argv.includes("--dry");
const OUT = resolve(
  arg(
    "out",
    new URL("../app/model/canary-reference.json", import.meta.url).pathname,
  ),
);
const N_PREDICT = Number(arg("n", "20"));

// The WHOLE system prompt (1333 tokens), on purpose: the Intel iGPU computes shorter prompts correctly and gives garbage
// from somewhere between 837 and 881 tokens on (measured, reports/2026-11-24-canary/study), and a real job's first
// turn is this long. A canary that is shorter than the real workload would pass on a path that fails the real job.
// --paragraphs picks a subset, only for experiments like that bisection.
const PARAGRAPHS = readFileSync(
  new URL("../protocol/prompts/system-v1.txt", import.meta.url),
  "utf8",
).split("\n\n");
export const SYSTEM = arg("paragraphs", "0,1,2,3,4,5,6")
  .split(",")
  .map((i) => PARAGRAPHS[Number(i)])
  .join("\n\n");
export const USER = `{"request": "Cut the first 2 seconds off", "inputs": [{"id": "clip", "probe": {"container": "mov,mp4,m4a,3gp,3g2,mj2", "duration_s": 6.0, "size_bytes": 200000, "streams": [{"index": 0, "type": "video", "codec": "h264", "width": 640, "height": 360, "fps": 25.0, "pix_fmt": "yuv420p", "rotation": 0}, {"index": 1, "type": "audio", "codec": "aac", "sample_rate": 44100, "channels": 1}]}}], "outputs": ["out1"]}`;
const messages = [
  { role: "system", content: SYSTEM },
  { role: "user", content: USER },
];

const post = async (path, body) => {
  const r = await fetch(`${SERVER}${path}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  if (!r.ok) throw new Error(`${path}: HTTP ${r.status} ${await r.text()}`);
  return r.json();
};
const sha256 = (p) =>
  new Promise((ok, no) => {
    const h = createHash("sha256");
    createReadStream(p)
      .on("data", (d) => h.update(d))
      .on("end", () => ok(h.digest("hex")))
      .on("error", no);
  });

const prompt = renderChat(messages);
const promptTokens = (
  await post("/tokenize", {
    content: prompt,
    add_special: false,
    parse_special: true,
  })
).tokens;
const c = await post("/completion", {
  prompt,
  n_predict: N_PREDICT,
  temperature: 0,
  top_k: 1,
  seed: 1,
  cache_prompt: false,
  return_tokens: true,
  n_probs: 2,
});
const tokens = c.tokens;
const text = c.content;
// The browser compares token ids it gets by tokenising its own generated text, so the reference must survive that
// round trip: text -> ids (specials NOT parsed) must give back exactly `tokens`.
const again = (
  await post("/tokenize", {
    content: text,
    add_special: false,
    parse_special: false,
  })
).tokens;
const roundTrips = JSON.stringify(again) === JSON.stringify(tokens);
// How confident was each greedy step: log-probability gap between the best and second-best token (small = fragile).
const margins = (c.completion_probabilities ?? []).map((p) => {
  const t = p.top_logprobs ?? p.top_probs ?? [];
  const a = t[0]?.logprob ?? Math.log(t[0]?.prob ?? 1);
  const b = t[1]?.logprob ?? Math.log(t[1]?.prob ?? 1e-9);
  return Math.round((a - b) * 100) / 100;
});
const props = await (await fetch(`${SERVER}/props`)).json().catch(() => ({}));

const ref = {
  note: "Generated by scripts/make-canary-reference.mjs from native llama.cpp (CPU, greedy). Do not edit by hand.",
  model: { file: MODEL.file, sha256: MODEL.sha256 },
  llamaCpp: { build: props.build_info ?? null },
  ggufSha256Checked: GGUF
    ? (await sha256(GGUF)) === MODEL.sha256
    : "not checked (no --gguf)",
  prompt,
  promptTokenCount: promptTokens.length,
  maxTokens: N_PREDICT,
  tokens,
  text,
  roundTrips,
  stepMargins: margins,
};
console.log(
  JSON.stringify(
    { ...ref, prompt: undefined, promptChars: prompt.length },
    null,
    1,
  ),
);
if (!roundTrips) {
  console.error(
    "REFUSED: the reference text does not tokenise back to the reference ids",
  );
  process.exit(1);
}
if (ref.ggufSha256Checked === false) {
  console.error("REFUSED: the gguf does not have the app's sha256");
  process.exit(1);
}
if (!DRY) writeFileSync(OUT, JSON.stringify(ref, null, 2) + "\n");
